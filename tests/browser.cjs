const assert = require("node:assert/strict");
const { readFile } = require("node:fs/promises");
const { chromium } = require("playwright");

async function main() {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("http://127.0.0.1:8000");
    await page.getByRole("link", { name: /Sector Generator/ }).click();
    const generate = page.getByRole("button", { name: "Generate sector", exact: true });
    await page.locator(".hex").first().waitFor();
    const tradeRoutes = page.getByLabel("Generate trade routes?");
    const tradeLines = page.locator(".trade-routes line");
    assert.equal(await tradeRoutes.inputValue(), "no");
    await page.getByLabel("Add System Points of Interest?").selectOption("4");
    await generate.click();
    assert.equal(await page.locator(".hex").count(), 80);
    assert.equal(await tradeLines.count(), 0);
    const count = await page.locator(".hex.occupied").count();
    assert.ok(count >= 21 && count <= 30);
    assert.equal(await page.locator(".hex.occupied[aria-pressed=true]").count(), 1);
    assert.match(await page.locator("#generation-status").innerText(), new RegExp(`Generated ${count} systems`));
    const systemTags = page.locator("#world .planet-tags");
    assert.equal(await systemTags.getByText("System Tags", { exact: true }).count(), 1);
    const names = await systemTags.locator("h4").allTextContents();
    assert.equal(names.length, 2);
    assert.equal(new Set(names).size, 2);
    assert.equal(await page.locator("#world .inspector-attributes dd").last().innerText(), names.join(", "));
    const panel = page.locator("#world");
    await panel.getByRole("button", { name: "Edit", exact: true }).click();
    await panel.getByRole("button", { name: "Add planet", exact: true }).click();
    await panel.getByRole("textbox", { name: "Name", exact: true }).fill("Outer Reach");
    const mine = panel.locator("details").filter({ has: page.locator("summary", { hasText: /^Gas giant mine$/ }) });
    await mine.getByRole("button", { name: "Add gas giant mine", exact: true }).click();
    await mine.getByRole("button", { name: "Add gas giant mine", exact: true }).click();
    assert.equal(await mine.getByRole("textbox", { name: "Name", exact: true }).count(), 2);
    await panel.getByLabel("System tag 1", { exact: true }).fill("Custom System Hook");
    await panel.getByRole("button", { name: "Add system tag", exact: true }).click();
    await panel.getByLabel("System tag 3", { exact: true }).fill("Third System Hook");
    await panel.getByRole("button", { name: "Save", exact: true }).click();
    assert.equal(await systemTags.locator("h4").count(), 3);
    assert.equal(await panel.getByRole("button", { name: "Outer Reach", exact: true }).count(), 1);
    const mainWorld = page.locator(".inspector-group").filter({ hasText: "Main world" }).getByRole("button");
    assert.equal(await page.getByRole("textbox", { name: "World name", exact: true }).count(), 0);
    await page.locator(".inspector-entry").filter({ has: page.locator("small") }).nth(1).click();
    const locationTags = await panel.locator(".planet-tags h4").allTextContents();
    assert.equal(new Set(locationTags).size, 2);
    assert.equal(await panel.locator(".planet-tags h5").count(), 10);
    assert.match(await page.locator(".inspector-description").innerText(), /Occupants:[\s\S]+Situation:/);
    await panel.getByRole("button", { name: "Edit", exact: true }).click();
    const locationType = panel.getByRole("combobox", { name: "Location type", exact: true });
    const firstTag = panel.getByRole("combobox", { name: "Location tag 1", exact: true });
    assert.equal(await firstTag.inputValue(), locationTags[0]);
    const secondTag = panel.getByRole("combobox", { name: "Location tag 2", exact: true });
    await panel.getByRole("button", { name: "Reroll location tag 1", exact: true }).click();
    const rerolled = await firstTag.inputValue();
    assert.ok(rerolled && !locationTags.includes(rerolled));
    assert.equal(await secondTag.inputValue(), locationTags[1]);
    await panel.getByRole("button", { name: "Reroll location tag 2", exact: true }).click();
    const secondReroll = await secondTag.inputValue();
    assert.ok(secondReroll && secondReroll !== rerolled && secondReroll !== locationTags[1]);
    assert.equal(await firstTag.inputValue(), rerolled);
    const nextType = (await locationType.inputValue()) === "Research base" ? "Asteroid belt" : "Research base";
    await locationType.selectOption(nextType);
    assert.equal(await firstTag.inputValue(), "");
    const replacement = await firstTag.locator("option").nth(1).evaluate(option => option.value);
    assert.ok(replacement);
    await firstTag.selectOption(replacement);
    await panel.getByRole("button", { name: "Save", exact: true }).click();
    assert.deepEqual(await panel.locator(".planet-tags h4").allTextContents(), [replacement]);
    await page.getByRole("button", { name: "Back", exact: true }).click();
    await mainWorld.click();
    assert.equal(await page.locator(".planet-tags article").count(), 2);
    assert.equal(await page.getByRole("textbox", { name: "World name", exact: true }).count(), 0);
    const inspector = page.locator("#world");
    const edit = inspector.getByRole("button", { name: "Edit", exact: true });
    await edit.click();
    const worldName = page.getByRole("textbox", { name: "World name", exact: true });
    const originalName = await worldName.inputValue();
    await inspector.getByRole("button", { name: "New name for world name", exact: true }).click();
    assert.notEqual(await worldName.inputValue(), originalName);
    await worldName.fill("Discarded name");
    await inspector.getByRole("button", { name: "Cancel", exact: true }).click();
    assert.notEqual(await inspector.locator("h3").innerText(), "Discarded name");
    await edit.click();
    await page.getByRole("textbox", { name: "World name", exact: true }).fill("New Horizon");
    await page.getByRole("textbox", { name: "Tag 1", exact: true }).fill("Handwritten tag");
    await page.getByRole("button", { name: "Reroll atmosphere" }).click();
    assert.equal(await page.getByRole("textbox", { name: "Tag 1", exact: true }).inputValue(), "Handwritten tag");
    await inspector.getByRole("button", { name: "Save", exact: true }).click();
    await page.reload();
    await mainWorld.click();
    assert.equal(await page.locator(".planet-tags article").count(), 2);
    assert.equal(await inspector.locator("h3").innerText(), "New Horizon");
    assert.equal(await inspector.locator(".planet-tags h4").first().innerText(), "Handwritten tag");

    const downloadReady = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export JSON" }).click();
    const exported = await readFile(await (await downloadReady).path());
    await page.getByLabel("Sector size").selectOption("custom");
    await page.getByLabel("Width").fill("32");
    await page.getByLabel("Height").fill("40");
    await page.getByLabel("Star count").selectOption("scaled");
    await generate.click();
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal(await page.locator(".hex.occupied").count(), count);
    assert.equal(await inspector.locator("h3").innerText(), "New Horizon");
    await tradeRoutes.selectOption("yes");
    await generate.click();
    await page.getByRole("button", { name: "Replace and generate" }).click();
    assert.equal(await page.locator(".hex").count(), 1280);
    const largeCount = await page.locator(".hex.occupied").count();
    assert.ok(largeCount >= 336 && largeCount <= 480);
    const routeCount = await tradeLines.count();
    assert.ok(routeCount > 0);
    await page.reload();
    assert.equal(await tradeRoutes.inputValue(), "yes");
    assert.equal(await tradeLines.count(), routeCount);
    const routeVisibility = page.getByRole("checkbox", { name: "Trade Routes", exact: true });
    const nameVisibility = page.getByRole("checkbox", { name: "System Names", exact: true });
    const nameLabels = page.locator(".hex.occupied .hex-system-name");
    assert.equal(await nameLabels.count(), largeCount);
    assert.equal(await page.locator(".hex:not(.occupied) .hex-system-name").count(), 0);
    assert.ok(await nameLabels.first().isVisible());
    const routeLayer = page.locator(".trade-routes");
    await routeVisibility.uncheck();
    assert.equal(await routeLayer.evaluate(layer => getComputedStyle(layer).display), "none");
    assert.ok(await nameLabels.first().isVisible());
    await nameVisibility.uncheck();
    await page.reload();
    assert.equal(await nameLabels.first().isVisible(), false);
    assert.equal(await page.locator("#trade-route-key").isVisible(), false);
    await routeVisibility.check();
    assert.notEqual(await routeLayer.evaluate(layer => getComputedStyle(layer).display), "none");
    assert.equal(await nameLabels.first().isVisible(), false);
    await nameVisibility.check();
    assert.ok(await nameLabels.first().isVisible());
    await page.locator('[data-column="32"][data-row="40"]').click();
    await page.keyboard.press("ArrowUp");
    assert.match(await page.locator("#selection").innerText(), /3239/);
    const overflow = await page.evaluate(() => {
      document.scrollingElement.scrollLeft = 0;
      const width = document.documentElement.scrollWidth;
      const offenders = Array.from(document.querySelectorAll("main *"))
        .filter((el) => !el.closest(".map-window") && el.getBoundingClientRect().right > 390)
        .map((el) => [el.tagName, el.id, el.className, el.getBoundingClientRect().right]);
      return { width, offenders };
    });
    assert.equal(overflow.width, 390, JSON.stringify(overflow.offenders));

    const input = page.getByLabel("Import JSON");
    await input.setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from("{") });
    await page.getByText(/Could not import/).waitFor();
    assert.equal(await page.locator(".hex").count(), 1280);
    page.once("dialog", (dialog) => dialog.accept());
    await input.setInputFiles({ name: "sector.json", mimeType: "application/json", buffer: exported });
    await page.getByText("Sector imported.").waitFor();
    assert.equal(await tradeRoutes.inputValue(), "no");
    assert.equal(await tradeLines.count(), 0);
    await mainWorld.click();
    assert.equal(await page.locator(".planet-tags article").count(), 2);
    assert.equal(await page.locator(".hex").count(), 80);
    assert.equal(await inspector.locator("h3").innerText(), "New Horizon");
    assert.equal(await inspector.locator(".planet-tags h4").first().innerText(), "Handwritten tag");
    const popupReady = page.waitForEvent("popup");
    await page.getByRole("link", { name: /Tag editor/ }).click();
    const tags = await popupReady;
    await tags.getByRole("button", { name: "Abandoned Colony · Planet · Book", exact: true }).click();
    assert.equal(await tags.getByRole("textbox", { name: "Name", exact: true }).isEnabled(), false);
    assert.equal(await tags.getByRole("button", { name: "Save tag" }).isVisible(), false);
    await tags.getByRole("combobox", { name: "Filter by tag type" }).selectOption("Moon");
    await tags.getByRole("button", { name: "New tag" }).click();
    assert.equal(await tags.getByRole("combobox", { name: "Tag type", exact: true }).inputValue(), "Moon");
    await tags.getByRole("textbox", { name: "Name", exact: true }).fill("Signal Dunes");
    await tags.getByRole("textbox", { name: "Enemies", exact: true }).fill("A rival survey team");
    await tags.getByRole("button", { name: "Save tag" }).click();
    await tags.getByText("Tag saved.", { exact: true }).waitFor();
    await tags.reload();
    await tags.getByRole("button", { name: "Signal Dunes · Moon", exact: true }).click();
    assert.equal(await tags.getByRole("textbox", { name: "Enemies", exact: true }).inputValue(), "A rival survey team");
    const tagType = tags.getByRole("combobox", { name: "Tag type", exact: true });
    for (const type of ["Deep-space station", "Asteroid base", "Remote moon base", "Ancient orbital ruin", "Research base", "Asteroid belt", "Gas giant mine", "Refuelling station"]) {
      assert.equal(await tagType.getByRole("option", { name: type, exact: true }).count(), 1);
    }
    await tagType.selectOption("");
    await tags.getByRole("textbox", { name: "Custom tag type" }).fill("Anomaly");
    await tags.getByRole("button", { name: "Save tag" }).click();
    await tags.getByRole("button", { name: "Signal Dunes · Anomaly", exact: true }).waitFor();
    tags.once("dialog", dialog => dialog.accept());
    await tags.getByRole("button", { name: "Delete tag" }).click();
    await tags.getByText("Tag deleted.", { exact: true }).waitFor();
    const routeFixture = JSON.parse(exported);
    routeFixture.selectedHex = { column: 1, row: 1 };
    routeFixture.generateTradeRoutes = false;
    routeFixture.tradeRoutes = [];
    routeFixture.systems = [
      ["origin", "Origin", 1], ["near", "Near", 2], ["edge", "Edge", 4], ["far", "Far", 5],
    ].map(([id, name, column]) => ({
      id, name, column, row: 1, ruleset: routeFixture.ruleset, mainWorld: null,
    }));
    page.once("dialog", dialog => dialog.accept());
    await input.setInputFiles({
      name: "routes.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(routeFixture)),
    });
    await page.getByRole("heading", { name: "Origin", exact: true }).waitFor();
    await page.getByRole("button", { name: "Add Trade Route" }).click();
    const destination = page.getByRole("combobox", { name: "Destination", exact: true });
    assert.deepEqual(await destination.locator("option").evaluateAll(options => options.map(option => option.value)),
      ["", "near", "edge"]);
    await destination.selectOption("near");
    await page.getByRole("button", { name: "Save route" }).click();
    assert.equal(await tradeLines.count(), 1);
    await page.getByRole("button", { name: "Edit route to Near" }).click();
    await destination.selectOption("edge");
    await page.getByRole("button", { name: "Save route" }).click();
    await page.reload();
    await page.getByRole("button", { name: "Edit route to Edge" }).waitFor();
    page.once("dialog", dialog => dialog.accept());
    await page.getByRole("button", { name: "Delete route to Edge" }).click();
    assert.equal(await tradeLines.count(), 0);
    await page.reload();
    await page.getByText("No trade routes.", { exact: true }).waitFor();
    assert.deepEqual(errors, []);

    const tpv = await browser.newPage();
    const tpvErrors = [];
    tpv.on("pageerror", error => tpvErrors.push(error.message));
    await tpv.addInitScript(() => { Math.random = () => 0.75; });
    await tpv.goto("http://127.0.0.1:8000/sector/");
    await tpv.getByLabel("Generation rules").selectOption("perilous-void");
    await tpv.getByRole("button", { name: "Generate sector", exact: true }).click();
    assert.equal(await tpv.locator(".hex").count(), 100);
    assert.equal(await tpv.locator("#tpv-chart tbody tr").count(), 20);
    const divider = tpv.getByRole("separator", { name: "Resize map and subsector list" });
    const mapStage = tpv.locator(".map-stage");
    const originalHeight = (await mapStage.boundingBox()).height;
    await divider.press("ArrowUp");
    assert.ok((await mapStage.boundingBox()).height < originalHeight);
    await divider.press("End");
    assert.ok((await mapStage.boundingBox()).height > originalHeight);
    const lastHex = tpv.locator(".hex.occupied").last();
    await lastHex.dispatchEvent("click");
    const chosen = [await lastHex.getAttribute("data-column"), await lastHex.getAttribute("data-row")]
      .map(part => part.padStart(2, "0")).join("");
    assert.equal(await tpv.locator("#tpv-chart button[aria-current=true]").innerText(), chosen);
    assert.ok(await tpv.locator("#tpv-chart").evaluate(list => list.scrollTop > 0));
    await tpv.locator(".hex:not(.occupied)").first().dispatchEvent("click");
    assert.equal(await tpv.locator("#tpv-chart button[aria-current=true]").count(), 0);
    await tpv.locator("#tpv-chart tbody button").first().click();
    const selectedSystem = tpv.locator(".hex.occupied[aria-pressed=true]");
    const hexFill = () => selectedSystem.locator("polygon").evaluate(hex => getComputedStyle(hex).fill);
    assert.equal(await selectedSystem.getAttribute("data-system-status"), "Wild");
    const wildFill = await hexFill();
    await tpv.getByLabel("System status").selectOption("Core");
    await tpv.getByRole("button", { name: "Develop System" }).click();
    await tpv.locator("#tpv-profile .tpv-orbits").waitFor();
    assert.equal(await tpv.locator("#sector-chart-layout").isVisible(), false);
    assert.equal(await tpv.locator(".map-stage").isVisible(), false);
    assert.equal(await tpv.locator("#tpv-chart").isVisible(), false);
    assert.equal(await tpv.locator("#tpv-profile .tpv-orbits section").count(), 11);
    assert.equal(await selectedSystem.getAttribute("data-system-status"), "Core");
    assert.notEqual(await hexFill(), wildFill);
    const developedRows = tpv.locator("#tpv-profile tbody tr");
    const worldDetails = await developedRows.locator("td:last-child").allTextContents();
    assert.ok(worldDetails.length > 0);
    assert.ok(worldDetails.every(text => /G .+A .+W .+L .+R /.test(text)));
    const planet = tpv.locator(".tpv-orbit-marker").filter({ has: tpv.locator(".tpv-planet") }).first();
    const planetName = await planet.innerText();
    await planet.click();
    await tpv.getByRole("heading", { name: `${planetName.trim()} · World Profile`, exact: true }).waitFor();
    await tpv.locator(".tpv-world-globe + section").getByRole("heading", { name: "Sites and Locations", exact: true }).waitFor();
    await tpv.locator(".sector-details").getByRole("heading", { name: "World Details", exact: true }).waitFor();
    await tpv.getByRole("button", { name: "System Profile", exact: true }).click();
    assert.deepEqual(await developedRows.locator("td:last-child").allTextContents(), worldDetails);
    await tpv.reload();
    await tpv.getByRole("button", { name: "Open System Profile" }).click();
    await tpv.locator("#tpv-profile .tpv-orbit-marker").first().waitFor();
    assert.deepEqual(await developedRows.locator("td:last-child").allTextContents(), worldDetails);
    await tpv.getByLabel("System status", { exact: true }).selectOption("Frontier");
    assert.match(await tpv.locator("#tpv-profile > p").innerText(), /· Frontier ·/);
    assert.equal(await selectedSystem.getAttribute("data-system-status"), "Frontier");
    assert.deepEqual(await developedRows.locator("td:last-child").allTextContents(), worldDetails);
    await tpv.reload();
    assert.equal(await tpv.getByLabel("System status", { exact: true }).inputValue(), "Frontier");
    await tpv.getByRole("button", { name: "Open System Profile" }).click();
    await tpv.getByRole("button", { name: "Redevelop System", exact: true }).click();
    await tpv.getByLabel("New system status").selectOption("Wild");
    await tpv.locator("#tpv-profile").getByRole("button", { name: "Cancel", exact: true }).click();
    assert.deepEqual(await developedRows.locator("td:last-child").allTextContents(), worldDetails);
    await tpv.getByRole("button", { name: "Redevelop System", exact: true }).click();
    await tpv.getByLabel("New system status").selectOption("Wild");
    await tpv.getByRole("button", { name: "Confirm Redevelopment" }).click();
    assert.match(await tpv.locator("#tpv-profile > p").innerText(), /· Wild ·/);
    assert.notDeepEqual(await developedRows.locator("td:last-child").allTextContents(), worldDetails);
    assert.equal(await selectedSystem.getAttribute("data-system-status"), "Wild");
    assert.equal(await hexFill(), wildFill);
    await tpv.reload();
    await tpv.getByRole("button", { name: "Open System Profile" }).click();
    assert.match(await tpv.locator("#tpv-profile > p").innerText(), /· Wild ·/);
    await tpv.getByRole("button", { name: "Sector Chart", exact: true }).click();
    await tpv.locator("#tpv-chart").waitFor();
    assert.ok(await tpv.locator(".map-stage").isVisible());
    await tpv.getByRole("button", { name: "Setting Overview", exact: true }).click();
    const factionName = tpv.getByLabel("New interstellar society name");
    assert.ok(await factionName.inputValue());
    await factionName.fill("The Silver Dawn");
    await tpv.getByRole("button", { name: "Develop Interstellar Society" }).click();
    const profile = tpv.locator(".tpv-setting-society");
    await profile.getByRole("heading", { name: "The Silver Dawn" }).waitFor();
    await profile.getByText("Interstellar", { exact: true }).waitFor();
    assert.match(await profile.locator("p").last().innerText(), /^THE SILVER DAWN:.* B Unassigned, R Interstellar,/);
    await profile.getByLabel("Faction name", { exact: true }).fill("Order of the Cinder Arc");
    await profile.getByRole("button", { name: "Save Name" }).click();
    await tpv.reload();
    await tpv.getByRole("button", { name: "Setting Overview", exact: true }).click();
    await profile.getByRole("heading", { name: "Order of the Cinder Arc" }).waitFor();
    await profile.getByRole("heading", { name: "Faction Notation" }).waitFor();
    assert.deepEqual(tpvErrors, []);
  } finally {
    await browser.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
